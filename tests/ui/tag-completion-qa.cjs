const { launchBrowser } = require('./browser-runtime.cjs')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const out = '.superloopy/evidence/frontend/tags'
;(async () => {
  fs.mkdirSync(out, { recursive: true })
  const browser = await launchBrowser()
  const page = await browser.newPage({ viewport: { width: 1280, height: 850 } })
  const errors = []
  const passed = []
  page.on('pageerror', (e) => errors.push(e.message))
  const a = page.getByPlaceholder('첫 번째 태그 입력')
  const b = page.getByPlaceholder('두 번째 태그 입력')
  const popup = page.locator('[data-tag-popup]')
  const first = popup.getByRole('option').first()
  const ready = async (input = a, text = 'sm') => {
    await input.fill('')
    await input.fill(text)
    await page.waitForFunction(
      () => document.querySelector('[role=listbox]')?.getAttribute('aria-busy') === 'false'
    )
    await first.waitFor()
    await page.waitForTimeout(180)
  }
  const closed = async () => {
    assert.equal(await popup.count(), 0)
  }
  try {
    await page.goto('http://127.0.0.1:5189/tag-completion.html')
    await ready()
    await a.press('Enter')
    assert.equal(await a.inputValue(), 'smile, ')
    await closed()
    passed.push('Enter accepts first ready suggestion')
    await a.press('Control+z')
    assert.equal(await a.inputValue(), 'sm')
    passed.push('native Ctrl+Z restores original token')
    await a.press('Escape')
    await a.fill('')
    await ready()
    await a.press('Shift+Enter')
    assert.equal(await a.inputValue(), 'sm\n')
    await closed()
    passed.push('Shift+Enter inserts newline')
    await ready()
    await a.press('ArrowDown')
    await a.press('Tab')
    assert.equal(await a.inputValue(), 'smirk, ')
    passed.push('arrow selection + Tab')
    await ready()
    await first.click()
    assert.equal(await a.inputValue(), 'smile, ')
    await page.getByRole('button', { name: '실행취소', exact: true }).last().click()
    assert.equal(await a.inputValue(), 'sm')
    passed.push('pointer click + undo toast')
    await a.press('Escape')
    await a.fill('')
    await ready()
    await a.dispatchEvent('compositionstart')
    await a.fill('심백안')
    await page.waitForTimeout(250)
    await a.dispatchEvent('keydown', {
      key: 'Enter',
      code: 'Enter',
      keyCode: 229,
      isComposing: true
    })
    assert.equal(await a.inputValue(), '심백안')
    await a.dispatchEvent('compositionend', { data: '심백안' })
    await a.dispatchEvent('keyup', { key: 'Enter', code: 'Enter' })
    await page.waitForTimeout(330)
    assert.equal(await a.inputValue(), 'smile, ')
    passed.push('one IME Enter inserts once after composition commits')
    await ready()
    const box = await first.boundingBox()
    await page.mouse.move(box.x + 30, box.y + 15)
    await page.mouse.down()
    await page.mouse.move(box.x + 70, box.y + 15)
    await page.mouse.up()
    assert.equal(await a.inputValue(), 'sm')
    passed.push('drag inside row does not insert')
    await page.mouse.click(1100, 700)
    await closed()
    await a.fill('slow')
    await page.waitForTimeout(160)
    await page.getByTestId('outside').click()
    await page.waitForTimeout(700)
    await closed()
    assert.equal(await a.inputValue(), 'slow')
    passed.push('outside click invalidates in-flight response')
    await a.fill('slowx')
    await a.press('Escape')
    await page.waitForTimeout(350)
    await closed()
    passed.push('Escape cancels pending debounce')
    await ready(a, 'sm')
    await a.fill('slow')
    assert.equal(await first.isDisabled(), true)
    await a.press('Enter')
    assert.equal(await a.inputValue(), 'slow')
    await page.waitForTimeout(750)
    assert.equal(await a.inputValue(), 'smile, ')
    await closed()
    passed.push('Enter during search waits for the current result without a newline')
    await ready()
    await b.fill('blue')
    await page.waitForTimeout(350)
    assert.equal(await popup.count(), 1)
    await b.press('Enter')
    assert.equal(await b.inputValue(), 'blue eyes, ')
    assert.equal(await a.inputValue(), 'sm')
    passed.push('two editors never share stale candidates')
    await ready()
    await a.press('ArrowLeft')
    await closed()
    passed.push('cursor movement dismisses old replacement range')
    await a.fill('')
    await a.press('Control+Space')
    await page.waitForTimeout(200)
    assert.match(await first.textContent(), /blue eyes/)
    assert.equal(await page.getByRole('button', { name: '자주 사용', exact: true }).count(), 0)
    assert.match(await popup.textContent(), /smile/)
    await page.screenshot({ path: `${out}/frequent-dark.png` })
    await first.click()
    assert.equal(await a.inputValue(), 'blue eyes, ')
    await ready(a, 'blue')
    const names = await popup.getByRole('option').allTextContents()
    assert.match(names[0], /blue eyes/)
    assert.ok(names.slice(2).some((s) => s.includes('smile')))
    assert.equal(names.filter((s) => s.includes('blue eyes')).length, 1)
    await page.screenshot({ path: `${out}/unified-recommendations.png` })
    passed.push('unified relevance then recent/frequent list, no tabs or duplicates')
    await ready()
    await page.getByRole('button', { name: '한글 뜻 편집', exact: true }).click()
    await page.getByRole('dialog').waitFor()
    await page.getByRole('textbox').fill('웃는 얼굴, 방긋')
    await page.getByRole('button', { name: '확인', exact: true }).click()
    await page.getByRole('dialog').waitFor({ state: 'hidden' })
    await a.fill('')
    await ready()
    assert.match(await first.textContent(), /웃는 얼굴, 방긋/)
    passed.push('Korean alias edit dialog and immediate updated display')
    await a.fill('zzzz')
    await page.getByText('일치하는 태그가 없어요.', { exact: false }).waitFor()
    await page.screenshot({ path: `${out}/empty.png` })
    await a.fill('error')
    await page.getByText('검색하지 못했어요.', { exact: false }).waitFor()
    passed.push('empty and failed searches recover visibly')
    for (const width of [390, 768, 1280]) {
      await page.setViewportSize({ width, height: 850 })
      await a.fill('')
      await ready()
      const bounds = await popup.boundingBox()
      assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width + 1)
      assert.ok(bounds.y >= 0 && bounds.y + bounds.height <= 851)
      const heights = await page
        .getByRole('option')
        .evaluateAll((rows) => rows.map((r) => r.getBoundingClientRect().height))
      assert.ok(heights.every((h) => h === 48))
      await page.screenshot({ path: `${out}/search-${width}.png` })
    }
    await page.evaluate(() => (document.documentElement.dataset.theme = 'light'))
    await page.waitForTimeout(350)
    await page.screenshot({ path: `${out}/search-light.png` })
    passed.push('390/768/1280 viewport containment; fixed rows; light/dark')
    await page.goto('http://127.0.0.1:5189/placement.html?mode=addition&tags=1')
    await page.getByRole('button', { name: '넓게 배치', exact: true }).click()
    const dialog = page.getByRole('dialog').last()
    await dialog.getByRole('button', { name: /, X / }).first().click()
    const ta = dialog.locator('textarea').first()
    await ready(ta)
    await page.screenshot({ path: `${out}/nested-placement.png` })
    await first.click()
    assert.equal(await ta.inputValue(), 'smile, ')
    assert.equal(await page.getByRole('dialog', { includeHidden: true }).count(), 2)
    await ready(ta, 'blue')
    await ta.press('Enter')
    assert.equal(await ta.inputValue(), 'blue eyes, ')
    await ready(ta)
    await ta.press('Escape')
    await closed()
    assert.equal(await page.getByRole('dialog', { includeHidden: true }).count(), 2)
    passed.push(
      'nested actual AdditionDialog > enlarged placement: click, Enter, Escape retain parents'
    )
    assert.deepEqual(errors, [])
    fs.writeFileSync(`${out}/results.json`, JSON.stringify({ passed, errors }, null, 2))
    console.log(JSON.stringify({ passed, errors }, null, 2))
  } catch (error) {
    await page.screenshot({ path: `${out}/failure.png` })
    console.error('Passed before failure:', passed)
    throw error
  } finally {
    await browser.close()
  }
})().catch((e) => {
  console.error(e)
  process.exit(1)
})
